CREATE OR REPLACE FUNCTION insert_completion_usage_event_sp(
	p_usage_event_key uuid,
	p_session_id integer,
	p_provider text,
	p_transport text,
	p_model_name text,
	p_reasoning_level text,
	p_provider_client_type text,
	p_credential_source text,
	p_credential_profile_id text,
	p_credential_display_name text,
	p_credential_fingerprint text,
	p_effective_base_url text,
	p_provider_request_id text,
	p_provider_response_id text,
	p_input_tokens integer,
	p_output_tokens integer,
	p_reasoning_tokens integer,
	p_cached_tokens integer,
	p_total_tokens integer,
	p_latency_ms integer,
	p_operation_reference_id text,
	p_compaction_epoch integer,
	p_compaction_epoch_key text,
	p_provider_limit_snapshot_usage_event_id integer,
	p_data text)
RETURNS TABLE ("UsageEventID" integer)
LANGUAGE plpgsql AS $$
DECLARE
	existing usage_events%ROWTYPE;
BEGIN
	IF p_usage_event_key IS NULL THEN RAISE EXCEPTION 'UsageEventKey is required.'; END IF;
	IF COALESCE(btrim(p_operation_reference_id), '') = '' THEN RAISE EXCEPTION 'OperationReferenceID is required.'; END IF;
	IF p_input_tokens < 0 OR p_output_tokens < 0 OR p_reasoning_tokens < 0 OR p_cached_tokens < 0 OR p_total_tokens < 0 OR p_latency_ms < 0 THEN
		RAISE EXCEPTION 'Completion usage counters cannot be negative.';
	END IF;

	INSERT INTO usage_events(usage_event_key, session_id, message_id, provider, transport, model_name, reasoning_level,
		provider_client_type, credential_source, credential_profile_id, credential_display_name, credential_fingerprint,
		effective_base_url, provider_request_id, provider_response_id, input_tokens, output_tokens, reasoning_tokens,
		cached_tokens, total_tokens, latency_ms, usage_operation, operation_reference_id, compaction_epoch,
		compaction_epoch_key, provider_limit_snapshot_usage_event_id, status, error_code, data, date_created, last_updated)
	VALUES(p_usage_event_key, p_session_id, NULL, p_provider, p_transport, p_model_name, p_reasoning_level,
		p_provider_client_type, p_credential_source, p_credential_profile_id, p_credential_display_name, p_credential_fingerprint,
		p_effective_base_url, p_provider_request_id, p_provider_response_id, p_input_tokens, p_output_tokens, p_reasoning_tokens,
		p_cached_tokens, p_total_tokens, p_latency_ms, 'completion', p_operation_reference_id, p_compaction_epoch,
		p_compaction_epoch_key, p_provider_limit_snapshot_usage_event_id, 'succeeded', NULL, p_data, now(), now())
	ON CONFLICT (session_id, usage_event_key) WHERE usage_event_key IS NOT NULL DO NOTHING;

	SELECT * INTO existing FROM usage_events WHERE session_id = p_session_id AND usage_event_key = p_usage_event_key;
	IF FOUND THEN
		IF existing.usage_operation <> 'completion' OR existing.status <> 'succeeded'
			OR existing.operation_reference_id IS DISTINCT FROM p_operation_reference_id
			OR existing.provider IS DISTINCT FROM p_provider OR existing.transport IS DISTINCT FROM p_transport
			OR existing.model_name IS DISTINCT FROM p_model_name OR existing.input_tokens <> p_input_tokens
			OR existing.output_tokens <> p_output_tokens OR existing.reasoning_tokens <> p_reasoning_tokens
			OR existing.cached_tokens <> p_cached_tokens OR existing.total_tokens <> p_total_tokens THEN
			RAISE EXCEPTION 'UsageEventKey already exists with different completion usage.';
		END IF;
		RETURN QUERY SELECT existing.usage_event_id;
		RETURN;
	END IF;
	RAISE EXCEPTION 'Completion usage insert did not produce a row.';
END;
$$;

CREATE OR REPLACE FUNCTION get_completion_usage_ledger_snapshot_sp(p_session_id integer, p_turn_key text, p_current_compaction_epoch integer)
RETURNS TABLE (
	"TurnCompletionCount" bigint, "TurnInputTokens" bigint, "TurnOutputTokens" bigint, "TurnReasoningTokens" bigint, "TurnCachedTokens" bigint, "TurnTotalTokens" bigint,
	"LifetimeCompletionCount" bigint, "LifetimeInputTokens" bigint, "LifetimeOutputTokens" bigint, "LifetimeReasoningTokens" bigint, "LifetimeCachedTokens" bigint, "LifetimeTotalTokens" bigint,
	"CurrentEpochCompletionCount" bigint, "CurrentEpochInputTokens" bigint, "CurrentEpochOutputTokens" bigint, "CurrentEpochReasoningTokens" bigint, "CurrentEpochCachedTokens" bigint, "CurrentEpochTotalTokens" bigint)
LANGUAGE sql AS $$
	SELECT
		COUNT(*) FILTER (WHERE operation_reference_id = p_turn_key),
		COALESCE(SUM(input_tokens::bigint) FILTER (WHERE operation_reference_id = p_turn_key), 0),
		COALESCE(SUM(output_tokens::bigint) FILTER (WHERE operation_reference_id = p_turn_key), 0),
		COALESCE(SUM(reasoning_tokens::bigint) FILTER (WHERE operation_reference_id = p_turn_key), 0),
		COALESCE(SUM(cached_tokens::bigint) FILTER (WHERE operation_reference_id = p_turn_key), 0),
		COALESCE(SUM(total_tokens::bigint) FILTER (WHERE operation_reference_id = p_turn_key), 0),
		COUNT(*), COALESCE(SUM(input_tokens::bigint), 0), COALESCE(SUM(output_tokens::bigint), 0),
		COALESCE(SUM(reasoning_tokens::bigint), 0), COALESCE(SUM(cached_tokens::bigint), 0), COALESCE(SUM(total_tokens::bigint), 0),
		COUNT(*) FILTER (WHERE compaction_epoch = p_current_compaction_epoch),
		COALESCE(SUM(input_tokens::bigint) FILTER (WHERE compaction_epoch = p_current_compaction_epoch), 0),
		COALESCE(SUM(output_tokens::bigint) FILTER (WHERE compaction_epoch = p_current_compaction_epoch), 0),
		COALESCE(SUM(reasoning_tokens::bigint) FILTER (WHERE compaction_epoch = p_current_compaction_epoch), 0),
		COALESCE(SUM(cached_tokens::bigint) FILTER (WHERE compaction_epoch = p_current_compaction_epoch), 0),
		COALESCE(SUM(total_tokens::bigint) FILTER (WHERE compaction_epoch = p_current_compaction_epoch), 0)
	FROM usage_events
	WHERE session_id = p_session_id AND usage_operation = 'completion' AND status = 'succeeded';
$$;
