import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../lib/tool-contract.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { validateToolArguments: validate, toolContracts } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
assert.equal(validate('find_elements', { selector: 'button' }).code, 'QUERY_REQUIRED');
assert.equal(validate('find_elements', { query: 'button' }), undefined);
assert.equal(validate('find_elements', { query: 'button', text: 'DNS' }).code, 'UNKNOWN_ARGUMENT');
assert.equal(validate('click', { selector: 'body', text: 'Nameservers' }).code, 'UNKNOWN_ARGUMENT');
assert.equal(validate('click', { elementId: 'buffaly-dom-ref:v1:test:1' }), undefined);
assert.equal(validate('click', { selector: 'text=Nameservers' }).code, 'INVALID_SELECTOR');
assert.equal(validate('click', { x: 10, y: 20 }).code, 'UNKNOWN_ARGUMENT');
assert.equal(validate('get_attribute', { selector: '#nameservers', attribute: 'aria-selected' }).code, 'ATTRIBUTENAME_REQUIRED');
assert.equal(validate('get_attribute', { selector: '#nameservers', attributeName: 'aria-selected' }), undefined);
assert.equal(validate('get_dom_snapshot', { selector: 'button' }).code, 'UNKNOWN_ARGUMENT');
assert.equal(validate('wait', { milliseconds: 100 }).code, 'UNKNOWN_ARGUMENT');
assert.equal(validate('wait', { ms: 100 }), undefined);
